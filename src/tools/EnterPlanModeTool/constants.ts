/**
 * ============================================================================
 *  【文件总览】src/tools/EnterPlanModeTool/constants.ts
 * ============================================================================
 *
 *  一句话定位：
 *  整个目录里最小的一个文件，只做一件事——把工具名 'EnterPlanMode'
 *  抽成一个常量，供别处引用。
 *
 *  为什么要为一行字符串单开一个文件？（Java 同学会很熟悉）
 *  这就是 Java 项目里的「常量类」。工具名这个字符串会同时出现在好几个地方：
 *     · 工具定义本身（EnterPlanModeTool.ts 的 name 字段）
 *     · 权限判定逻辑（按工具名匹配规则）
 *     · 提示词 / UI 文案里引用
 *  如果不抽常量、各处硬编码字面量，那么将来改一次工具名，
 *  漏改任何一处都不会报错——权限判定会静默失效，这种 bug 极难排查。
 *  抽成常量后，改名只需要动这一行。
 *
 *  在架构中的位置：
 *      EnterPlanModeTool.ts  ──引用──>  本常量（注册为工具的 name）
 *      （同目录的其它文件、以及权限/UI 相关模块也可能引用）
 *
 *  本文件包含什么：
 *   1. ENTER_PLAN_MODE_TOOL_NAME   工具名常量，值为 'EnterPlanMode'
 *
 *  TS 语法速查（Java 工程师视角）：
 *   - `export`  ：对外公开。≈ Java 的 `public`。
 *                 不写 export 的声明只在当前文件内可见（≈ Java 的包级私有）。
 *   - `const`   ：声明一个**不可重新赋值**的引用。≈ Java 的 `final`。
 *                 注意和 Java final 一样：只保证"这个变量指向谁"不变，
 *                 如果指向的是对象，对象内部字段照样能改。
 *   - 没有写 `: string` 类型标注——TS 能从右侧的字符串字面量**自动推断**
 *     出类型是 string。这叫「类型推断」，≈ Java 10+ 的 `var`。
 *     本仓库里多数常量会省略这种显而易见的类型标注。
 *   - `.js` 结尾的 import 路径（别处可见）：这个项目用 ESM + NodeNext 模块解析，
 *     要求 import 写完整扩展名，且源码是 .ts 却要写 .js。
 *     ≈ Java 编译后 class 文件包名要和源码一致那种"编译期/运行期路径错位"。
 */
