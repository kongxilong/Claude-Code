/**
 * ============================================================================
 *  【文件总览】src/tools/SendMessageTool/constants.ts
 * ============================================================================
 *
 *  【一句话定位】
 *  本文件只有一个常量：SendMessage 工具的名字字符串 'SendMessage'。
 *
 *  【在架构中的位置】
 *      SendMessageTool.ts（工具的 name 字段）  ← 引用这里的常量
 *      权限规则、UI、测试等其它模块也一样引用它。
 *
 *  【为什么一个字符串也要单独开一个文件？】
 *  工具名会出现在很多地方（工具注册、权限配置、UI 展示、日志、测试）。
 *  如果各处直接写死 'SendMessage' 这个字面量，将来改名就要全局搜索替换，
 *  漏掉一处就是一个难查的 bug。抽成常量后：
 *      - 改名只改这一行；
 *      - 拼错时**编译期就报错**（引用一个不存在的导出会直接编译失败），
 *        而写错字符串字面量只能等运行时才发现。
 *  ≈ Java 里把魔法字符串抽成 `public static final String XXX`。
 *
 * ---------------------------------------------------------------------------
 *  【TS 语法速查】
 * ---------------------------------------------------------------------------
 *  - `export const X = '...'`  导出常量。≈ Java 的 `public static final String X = "..."`。
 *  - `export` ≈ public，不写 export 就是模块内私有（≈ 包级私有）。
 *  - 注意：这里**没有**写 `: string` 类型标注，因为 TS 能从右边的字面量
 *    自动推导出类型（类型推导 ≈ Java 10 的 `var`，但 TS 里用得更普遍）。
 *  - `as const`（本文件没用到，顺带一提）：会把类型锁成字面量 'SendMessage'
 *    而不是宽泛的 string，用于需要精确匹配的场合。
 */
export const SEND_MESSAGE_TOOL_NAME = 'SendMessage'
