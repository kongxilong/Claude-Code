/**
 * ============================================================================
 *  【文件总览】src/services/skillSearch/telemetry.ts —— Skill 搜索的埋点上报（桩）
 * ============================================================================
 *
 *  一句话定位：
 *  把 Skill 搜索的调用情况（命中率、耗时、是否走远程）上报到遥测系统。
 *  开源版为空实现，什么都不做。
 *
 *  在架构中的位置：
 *      src/tools/SkillTool/SkillTool.ts
 *        └─> require('../../services/skillSearch/telemetry.js')
 *              └─> logSkillSearchTelemetry()            ← ★ 本文件
 *
 *  本文件包含什么：
 *   - logSkillSearchTelemetry()：同步空函数，返回 void。
 *
 *  【为什么是空的 / 为什么要单独一个文件】
 *  埋点（telemetry）用于产品侧观察功能真实使用情况，属于可观测性设施。
 *  单独成文件的好处：调用方只依赖这一个符号，换埋点后端时只改这一处。
 *  开源版不外发数据，所以留空——这也是尊重用户隐私的做法。
 *
 *  设计约束（重要）：埋点函数**永远不该抛异常、不该阻塞主流程**。
 *  就算埋点系统挂了，Skill 搜索本身也要照常工作。空实现天然满足这一点。
 *
 *  TS 语法速查：
 *   - `: void`  显式标注「没有返回值」，≈ Java 的 `void` 方法
 *   - `{}`      空函数体
 * ============================================================================
 */

